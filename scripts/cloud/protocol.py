"""Required provider surface, shared by CLI providers and the AWS SDK adapter.

Architecture is explicit in discovery, planning and launch. `owner=None` lists
all project-tagged leftovers; a supplied owner must filter at the provider.
Provider-specific quota, role, billing and risk policies are not transport policy.
`instance_state`, `allow_ssh` and `allow_hint` serve the operator-IP allowlist a
running instance's ssh depends on (cloud/allowlist.py): whether the instance is
still there, an add-only widening of this project's own ssh group for this
machine's current public address, and the exact provider call that would do it.
Optional hooks (reap, check_deadman, slot_holders, checkpoint) are capability
checked by the caller and deliberately excluded from this required surface.
"""
from typing import Any, Protocol, TYPE_CHECKING, runtime_checkable

if TYPE_CHECKING:
    from cloud.cloud_common import Offer


@runtime_checkable
class Provider(Protocol):
    name: str
    currency: str
    ssh_user: str
    home: str
    ssh_ports: list[int]
    default_regions: list[str]
    all_regions: list[str]
    label_suffix: str
    default_ssh_proxy: str
    min_lifetime_minutes: int

    def check_account(self) -> str: ...
    def default_types(self, arch: str, tier: str = "quick") -> list[str]: ...
    def offers(self, types: list[str], arch: str, regions: list[str]) -> list["Offer"]: ...
    def mainland(self, region: str) -> bool: ...
    def describe_plan(self, offer: "Offer", arch: str) -> list[str]: ...
    def launch(self, m: Any, ips: list[str], fresh_key: bool, max_minutes: int, arch: str) -> None: ...
    def find_launched(self, m: Any) -> str | None: ...
    def instance_state(self, m: Any) -> str | None: ...
    def allow_ssh(self, m: Any, ips: list[str]) -> str: ...
    def allow_hint(self, m: Any, ips: list[str]) -> str: ...
    def wait_ready(self, m: Any) -> None: ...
    def terminate(self, m: Any) -> bool: ...
    def terminate_hint(self, m: Any) -> str: ...
    def leftovers(self, regions: list[str], owner: str | None = None) -> list[tuple[str, str, str]]: ...
    def packages_script(self) -> str: ...
    def java_script(self) -> str: ...
    def public_ips(self, proxy: str) -> list[str]: ...
