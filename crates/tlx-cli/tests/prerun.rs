//! The compiled tier's shape pre-run evaluates the spec in the interpreter,
//! but must not print Print/PrintT output: only the search prints those
//! lines (as TLC does), as often as the interpreter alone.

use std::path::Path;

const SPEC: &str = r#"---- MODULE PreRun ----
EXTENDS Naturals, TLC
VARIABLE x
Init == x = 0
Next == PrintT("PRERUN-NEXT") /\ x' = (x + 1) % 4
Inv == Print("PRERUN-INV", x) < 100
====
"#;

const CFG: &str = "INIT Init\nNEXT Next\nINVARIANT Inv\n";

/// A directory holding the spec.
fn spec_dir() -> tlx_testkit::TempDir {
    tlx_testkit::TempDir::with_spec("prerun", SPEC, CFG)
}

/// The output of `tlx check` with `extra`: the whole text (stdout and
/// stderr), and its lines minus the compiled tier's `compile: ...` progress
/// lines.
fn run(dir: &Path, extra: &[&str]) -> (String, Vec<String>) {
    let out = tlx_testkit::tlx!().args(["check", "PreRun.tla", "-config", "PreRun.cfg"]).args(extra).dir(dir).run();
    let text = out.text();
    let lines = text.lines().filter(|l| !l.starts_with("compile:")).map(str::to_owned).collect();
    (text, lines)
}

/// How many lines were printed by a `Print`/`PrintT` with this text (a
/// string is displayed quoted).
fn printed(lines: &[String], text: &str) -> usize {
    let prefix = format!("\"{text}\"");
    lines.iter().filter(|l| l.starts_with(&prefix)).count()
}

#[test]
fn compiled_prerun_does_not_print() {
    let dir = spec_dir();
    let (_, plain) = run(&dir, &[]);
    let (compiled_raw, compiled) = run(&dir, &["-compile"]);
    assert!(compiled_raw.contains("compile: pre-run:"), "the compiled run did not pre-run:\n{compiled_raw}");
    // (Printing: the pre-run is not the search.)
    assert!(compiled_raw.contains("compile: lowering"), "the compiled run did not search:\n{compiled_raw}");
    let (next, inv) = (printed(&plain, "PRERUN-NEXT"), printed(&plain, "PRERUN-INV"));
    assert!(next > 0 && inv > 0, "the interpreter printed nothing:\n{plain:?}");
    assert_eq!(printed(&compiled, "PRERUN-NEXT"), next, "PrintT lines of -compile:\n{compiled:?}");
    assert_eq!(printed(&compiled, "PRERUN-INV"), inv, "Print lines of -compile:\n{compiled:?}");
}

/// Four registers with independent values: the layout is right after the
/// first states (the values come from a constant interval), so the BFS of
/// the pre-run stops once it has settled (`TLX_PRERUN_SETTLE`), well before
/// its state budget, with the same results.
const SETTLE_SPEC: &str = r#"---- MODULE Settle ----
EXTENDS Naturals
VARIABLES a, b, c, d
Init == a = 0 /\ b = 0 /\ c = 0 /\ d = 0
Next == \E i \in 0..9 : \/ a' = i /\ UNCHANGED <<b, c, d>>
                        \/ b' = i /\ UNCHANGED <<a, c, d>>
                        \/ c' = i /\ UNCHANGED <<a, b, d>>
                        \/ d' = i /\ UNCHANGED <<a, b, c>>
====
"#;

#[test]
fn prerun_stops_when_the_layout_settles() {
    let dir = tlx_testkit::TempDir::new("prerun");
    std::fs::write(dir.join("Settle.tla"), SETTLE_SPEC).unwrap();
    std::fs::write(dir.join("Settle.cfg"), "INIT Init\nNEXT Next\n").unwrap();
    let run = |settle: &str| {
        let out = tlx_testkit::tlx!()
            .args(["check", "Settle.tla", "-compile"])
            .env("TLX_PRERUN_SETTLE", settle)
            .env("TLX_PRERUN_MS", "60000")
            .dir(&dir)
            .run();
        out.text()
    };
    let (settled, full) = (run("1000"), run("0"));
    let prerun = |text: &str| text.lines().find(|l| l.starts_with("compile: pre-run:")).map(str::to_owned).unwrap_or_default();
    assert!(prerun(&settled).ends_with("states (layout settled)"), "{settled}");
    assert!(prerun(&full).ends_with(" 10000 states"), "{full}");
    let found = |text: &str| text.lines().find(|l| l.contains("distinct states found")).map(str::to_owned);
    assert_eq!(found(&settled), found(&full));
    assert!(found(&full).is_some_and(|l| l.contains(" 10000 distinct states")), "{full}");
    assert!(!settled.contains("layout miss"), "{settled}");
}

/// x = 1000 is only generated by transitions the ACTION_CONSTRAINT drops:
/// the search encodes it all the same, so the pre-run observes it too (on
/// one thread and on several), and the search has no layout miss.
const AC_SPEC: &str = r#"---- MODULE AC1 ----
EXTENDS Naturals
VARIABLES x
Init == x = 0
Next == x' = IF x = 2 THEN 1000 ELSE (x + 1) % 3
AC == x' < 100
====
"#;

#[test]
fn prerun_observes_successors_the_action_constraint_drops() {
    let dir = tlx_testkit::TempDir::with_spec("prerun", AC_SPEC, "INIT Init\nNEXT Next\nACTION_CONSTRAINT AC\n");
    for workers in ["1", "4"] {
        let out =
            tlx_testkit::tlx!().args(["check", "AC1.tla", "-config", "AC1.cfg", "-compile", "-workers", workers]).dir(&dir).run().text();
        assert!(out.contains("4 states generated, 3 distinct states found"), "-workers {workers}:\n{out}");
        assert!(!out.contains("layout miss"), "-workers {workers}:\n{out}");
    }
}

/// The search creates strings (`ToString`), so the pre-run is the search
/// itself, stopped by its state budget (`TLX_PRERUN`): among the 100
/// initial states (no more are generated), or after the successor that
/// reaches it; the search finds all 200 states. Within a budget
/// of 1000 states it explores them all, and its result is the run's,
/// unless `TLX_PRERUN_REUSE=0`.
const FAITHFUL_SPEC: &str = r#"---- MODULE Faithful ----
EXTENDS Naturals, TLC
VARIABLES a, s
Init == a \in 0..99 /\ s = "a"
Next == a' = (a + 1) % 100 /\ s' = ToString(a')
====
"#;

#[test]
fn the_faithful_prerun_stops_at_its_state_budget() {
    let dir = tlx_testkit::TempDir::with_spec("prerun", FAITHFUL_SPEC, "INIT Init\nNEXT Next\n");
    for (budget, reuse, seen) in [
        ("10", "1", "10 states"),
        ("150", "1", "150 states"),
        ("1000", "0", "200 states"),
        ("1000", "1", "200 states (the search: its result is the run's)"),
    ] {
        let out = tlx_testkit::tlx!()
            .args(["check", "Faithful.tla", "-config", "Faithful.cfg", "-compile", "-workers", "1"])
            .env("TLX_PRERUN", budget)
            .env("TLX_PRERUN_SETTLE", "0")
            .env("TLX_PRERUN_MS", "60000")
            .env("TLX_PRERUN_REUSE", reuse)
            .dir(&dir)
            .run()
            .text();
        let prerun = out.lines().find(|l| l.starts_with("compile: pre-run:")).unwrap_or_default();
        assert!(prerun.ends_with(&format!(", {seen}")), "TLX_PRERUN={budget}:\n{out}");
        assert!(out.contains("300 states generated, 200 distinct states found"), "TLX_PRERUN={budget}:\n{out}");
        assert_eq!(out.contains("compile: lowering"), !seen.contains("the search"), "TLX_PRERUN={budget}:\n{out}");
    }
}

/// A search that creates strings (`\o`) and ends early: an invariant
/// violation, a deadlock, a temporal property violated. Its pre-run is the
/// search; it ends before its budget, and its result is the run's,
/// with the same output as the compiled search (`TLX_PRERUN_REUSE=0`) and
/// the interpreter; not under the conditions the search's result could
/// differ from the pre-run's, nor when the pre-run does not record the
/// behavior graph (its liveness atoms create no strings).
const REUSE_SPEC: &str = r#"---- MODULE Reuse ----
EXTENDS Naturals, Sequences
VARIABLES x, log
Init == x = 0 /\ log = ""
Next == x < 6 /\ x' = x + 1 /\ log' = log \o "a"
Inv == x < 5
Prop == <>(log \o "a" = "aaaaaaaa")
Plain == <>(x = 7)
====
"#;

#[test]
fn a_prerun_that_ends_early_is_the_search() {
    let dir = tlx_testkit::TempDir::with_spec("prerun", REUSE_SPEC, "INIT Init\nNEXT Next\n");
    let inv = "INIT Init\nNEXT Next\nINVARIANT Inv\n";
    let cases: [(&str, &[&str], &[(&str, &str)], bool); 10] = [
        (inv, &[], &[], true),
        ("INIT Init\nNEXT Next\n", &[], &[], true),
        ("INIT Init\nNEXT Next\n", &["-deadlock"], &[], true),
        ("INIT Init\nNEXT Next\nPROPERTY Prop\n", &["-deadlock"], &[], true),
        ("INIT Init\nNEXT Next\nPROPERTY Plain\n", &["-deadlock"], &[], false),
        (inv, &["-workers", "2"], &[], false),
        (inv, &["-coverage", "1"], &[], false),
        (inv, &[], &[("TLX_CHECKPOINT_STATES", "2")], false),
        (inv, &[], &[("TLX_PARANOID", "1")], false),
        (inv, &[], &[("TLX_PRERUN_REUSE", "0")], false),
    ];
    for (cfg, args, env, reused) in cases {
        std::fs::write(dir.join("Reuse.cfg"), cfg).unwrap();
        let run = |extra: &[&str], env: &[(&str, &str)]| {
            let out = tlx_testkit::tlx!()
                .args(["check", "Reuse.tla", "-config", "Reuse.cfg"])
                .args(args)
                .args(extra)
                .envs(env.iter().copied())
                .dir(&dir)
                .run();
            (out.code, out.text())
        };
        let (code, out) = run(&["-compile"], env);
        let (want_code, want) = run(&[], &[]);
        let (compiled_code, compiled) = run(&["-compile"], &[("TLX_PRERUN_REUSE", "0")]);
        let what = format!("{cfg:?} {args:?} {env:?}:\n{out}");
        assert_eq!(out.contains("(the search: its result is the run's)"), reused, "{what}");
        assert_eq!(!out.contains("compile: lowering"), reused, "{what}");
        let results = |code: i32, out: &str| (code, tlx_testkit::cli::result_lines(out).into_iter().map(str::to_owned).collect::<Vec<_>>());
        assert_eq!(results(code, &out), results(want_code, &want), "{what}\n--- interpreter:\n{want}");
        assert_eq!(results(code, &out), results(compiled_code, &compiled), "{what}\n--- compiled search:\n{compiled}");
    }
}
