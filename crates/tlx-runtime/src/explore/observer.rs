//! Search observers: watching a breadth-first search (the states it finds,
//! the transitions it generates, the expansion of a state) without wrapping
//! the model, so that nothing the model provides can be lost on the way
//! (`-dump`, the search for the errors TLC reports in the liveness
//! predicates, the compiled tier's faithful pre-run, which a quiet observer
//! stops at its budget). `explore_observed` runs a search with an
//! observer; the other entry points have none, and their workers are
//! instantiated without the observer's hooks (`worker::expand`'s `OBS`).

use crate::model::ModelError;

/// Watches a search (`explore_observed`). The hooks are called on the
/// threads of the search (several workers: concurrently), in the order the
/// search does the work they report; with one worker that is TLC's order.
/// Only a search from the initial states is observed (not a resumed or
/// recovered one), and the re-execution of an error trace is not.
pub trait SearchObserver<S>: Sync {
    /// Whether the search records the behavior graph of the model's
    /// liveness atoms (`Caps::live_atoms`) as it does unobserved: an
    /// observer that evaluates the liveness predicates itself answers
    /// false, so that no second graph is recorded (and several workers
    /// choose the representatives of VIEW / SYMMETRY classes in BFS order,
    /// which recording the graph excludes).
    fn records_live_graph(&self) -> bool {
        true
    }

    /// Whether the successors of a state are generated all before any is
    /// processed, to be passed to `on_expanded` first (TLC evaluates the
    /// liveness predicates of a state before other workers can expand its
    /// successors).
    fn buffers(&self) -> bool {
        false
    }

    /// Whether the search is not the run's own (the compiled tier's
    /// pre-run): it then records no statistics (`-stats`), leaves the
    /// evaluation caches' allowance as it is, and neither rebuilds the
    /// trace of a failure nor builds the behavior graph (`Report::trace`
    /// and `Report::live_graph` stay empty).
    fn quiet(&self) -> bool {
        false
    }

    /// Whether a quiet search, at its end, still rebuilds the trace of a
    /// failure and builds the behavior graph (`Report::trace`,
    /// `Report::live_graph`): its report is then the run's (the compiled
    /// tier's faithful pre-run when it explored the whole state space).
    fn complete_results(&self) -> bool {
        false
    }

    /// Whether the search stops here, as if the state space ended (states
    /// not expanded are left in the queue, `Stats::left`), `distinct` being
    /// the distinct states found so far. Polled after each new initial
    /// state is checked (`init`: no more are generated, see
    /// `Model::init_states_while`), once all are, and with one worker
    /// exactly where a sequential search would test a budget: after each
    /// successor processed (the state being expanded processes no more,
    /// and records no liveness edges) and after each state expanded. Not
    /// after a failure, which stops the search first.
    fn stop(&self, _init: bool, _distinct: u64) -> bool {
        false
    }

    /// The `k`-th initial state generated (from 0), `s`, is a new state in
    /// the model, queued but not yet checked against invariants. An error stops the search as an
    /// error computing the initial states (after the initial states, as
    /// an error the model raises after enumerating them).
    fn on_init(&self, _s: &S, _k: u64) -> Result<(), ModelError> {
        Ok(())
    }

    /// State `s` (fingerprint `fp`, at BFS depth `depth`: 1 for an
    /// initial state) is about to be checked against the invariants: a new
    /// state, or one outside the model (CONSTRAINT / ACTION_CONSTRAINT,
    /// checked every time it is generated). `parent` is the fingerprint of
    /// the state whose expansion generated it; None for an initial state
    /// and for the representatives of VIEW / SYMMETRY classes chosen at the
    /// end of a level (several workers).
    fn on_new_state(&self, _s: &S, _fp: u64, _depth: u32, _parent: Option<u64>) {}

    /// The search processes a successor of fingerprint `to`, generated by
    /// action `action` from the state of fingerprint `from` (before any
    /// check), as soon as it is generated (unless the observer buffers).
    fn on_edge(&self, _from: u64, _to: u64, _action: u32) {}

    /// With `buffers`: the successors `succ` of `s` (with their actions),
    /// before they are processed; `complete`: they were generated without
    /// error. An error stops the search at `s`, unless processing a
    /// successor stops it first; it is reported before an error of the
    /// generation.
    fn on_expanded(&self, _s: &S, _succ: &[(S, u32)], _complete: bool) -> Result<(), ModelError> {
        Ok(())
    }
}
